def _node(x, y, left_edge, right_edge):
    return Node(nodetype="blue_node", minimap_pos=(x, y), can_fall=False, fall_dist_exceeds_vertical_tp=False,
                is_left_platform_edge=bool(left_edge), is_right_platform_edge=bool(right_edge))


def _direction(u, v, weight, x_allowance, y_allowance):
    (ux, uy), (vx, vy) = u.minimap_position, v.minimap_position
    letters = []
    if vx < ux and abs(vy - uy) <= y_allowance and ux - vx == weight:
        letters.append("L")
    if vx > ux and abs(vy - uy) <= y_allowance and vx - ux == weight:
        letters.append("R")
    if vy < uy and abs(vx - ux) <= x_allowance and uy - vy == weight:
        letters.append("U")
    if vy > uy and abs(vx - ux) <= x_allowance and vy - uy == weight:
        letters.append("D")
    assert letters, f"edge {u.minimap_position} -> {v.minimap_position} (weight {weight}) fits no direction"
    return "+".join(letters)


def _dump(pg, nodes):
    """(ordered edge tokens, in-edge order tokens) of the built graph; `nodes` is in creation order."""
    label = {n: i for i, n in enumerate(nodes)}
    graph = pg.graph
    assert set(graph.nodes()) == set(label)
    edges = [
        f"{label[u]}>{label[v]}#{key}:"
        f"{_direction(u, v, w, pg.edge_x_alignment_allowance, pg.edge_y_alignment_allowance)}:{w}"
        for u, v, key, w in graph.edges(keys=True, data="weight")
    ]
    in_edges = [f"{label[v]}<{label[u]}#{key}" for v in graph.nodes() for u, _, key in graph.in_edges(v, keys=True)]
    return edges, in_edges


def _synthetic_graph(nodes, order, params):
    in_order = nodes if order == "forward" else nodes[::-1]
    pg = PathGraph(node_map={n.uuid: n for n in in_order}, edge_y_alignment_allowance=params["y"],
                   edge_x_alignment_allowance=params["x"], max_horizontal_traversal_dist=params["h"],
                   max_vertical_traversal_dist=params["v"])
    assert is_successful(pg.buildGraph())
    return pg


@pytest.fixture(scope="module")
def ff2():
    # One MapleAgent for the module: the tests below only read it; each builds its own PathGraph over a copy of
    # its node_map (connectCharacterNode adds to the node_map it was given).
    agent = MapleAgent(characterClass=Kanna())
    assert agent.loadMap(FIXTURE) == Success(BuildOutcome.BUILT)
    nodes = sorted(agent.node_map.values(), key=lambda n: n.uuid)
    assert [n.uuid - nodes[0].uuid for n in nodes] == list(range(21))
    assert list(agent.node_map.values()) == nodes   # the loaded node_map order is the creation order
    return agent, nodes


def _ff2_graph(agent, nodes, order):
    in_order = nodes if order == "forward" else nodes[::-1]
    res = agent.buildPathGraphFor({n.uuid: n for n in in_order})
    assert is_successful(res)
    pg = res.unwrap()
    assert is_successful(pg.buildGraph())
    return pg


def _case_dump(case, order, ff2_agent_and_nodes=None):
    """Build `case` in `order` and return its dump."""
    base, _, params_name = case.partition("@")
    name, _, with_char = base.partition("+")
    if name == "ff2":
        agent, ff2_nodes = ff2_agent_and_nodes
        nodes = list(ff2_nodes)
        pg = _ff2_graph(agent, ff2_nodes, order)
        char_pos = FF2_CHAR_AT[int(with_char[len("char"):])] if with_char else None
    else:
        params = PARAMS[params_name or "kanna"]
        specs = _boundary_specs(params) if name == "boundaries" else SYNTHETIC[name]
        nodes = [_node(*spec) for spec in specs]
        pg = _synthetic_graph(nodes, order, params)
        char_pos = CHAR_AT[name] if with_char else None
    if char_pos is not None:
        char = CharacterNode(minimap_pos=char_pos)
        pg.connectCharacterNode(char)
        nodes.append(char)
    return _dump(pg, nodes)


CASES = (
    ["ff2"] + [f"ff2+char{i}" for i in range(len(FF2_CHAR_AT))]
    + list(SYNTHETIC) + ["boundaries"] + [f"{name}+char" for name in CHAR_AT]
    + ["generated_24@asym", "near_diagonal@asym", "platform_edges@asym", "boundaries@asym",
       "generated_24+char@asym"]
)


@pytest.mark.parametrize("order", ORDERS)
@pytest.mark.parametrize("case", CASES)
def test_ordered_edge_list_and_in_edge_order_are_unchanged(case, order, ff2):
    edges, in_edges = _case_dump(case, order, ff2)
    golden_edges, golden_in_edges = GOLDEN[f"{case}/{order}"]
    assert edges == golden_edges.split()
    assert in_edges == golden_in_edges.split()


