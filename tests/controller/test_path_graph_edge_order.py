def _generated_specs():
    """24 nodes from a fixed linear congruential generator (no random module, so the map never changes): x in
    30..69, y in 20..47, about an eighth of them flagged as a left and another eighth as a right platform end."""
    state = 217
    specs = []
    for _ in range(24):
        values = []
        for _ in range(4):
            state = (state * 1103515245 + 12345) % 2 ** 31
            values.append(state >> 8)
        x, y = 30 + values[0] % 40, 20 + values[1] % 28
        specs.append((x, y, int(values[2] % 8 == 0), int(values[3] % 8 == 0)))
    return specs


